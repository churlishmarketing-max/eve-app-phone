export function badgeFor(key: string): Badge {
  const cap = byKey.get(key);
  if (!cap) return "WORKSPACE_ONLY";
  return cap.host === "desk" ? "DESK" : "RUNNABLE";
}

/** Is this unit's runner wired and reachable from THIS brain right now? */
export function runnerLive(key: string): boolean {
  const cap = byKey.get(key);
  if (!cap) return false;
  if (cap.runner.kind === "tool") return os.ready();
  return true; // SDK workers and skills ride the same credentials the chat loop already uses
}

const norm = (s: string) => s.trim().toLowerCase().replace(/[\s_]+/g, "-").replace(/^the-/, "");

// "Perry White" / "perry_white" / " PERRY-WHITE " → "perry-white". Also
// resolves a roster or registry NAME word-for-word to its key so "Pennyworth"
// and "Jimmy Olsen" work. Never fuzzy — a near-miss is an unknown unit, and an
// unknown unit is a spoken error, not a guess.
export function resolveUnitKey(input: string, roster: readonly FleetUnit[]): string {
  const n = norm(input);
  if (byKey.has(n)) return n;
  const direct = roster.find((u) => u.key === n);
  if (direct) return direct.key;
  const byName = roster.find((u) => norm(u.name) === n);
  if (byName) return byName.key;
  const byRegName = REGISTRY.find((c) => norm(c.name) === n);
  return byRegName ? byRegName.key : n;
}

export interface DispatchRefusal {
  ok: false;
  code: "unit_unknown" | "unit_not_runnable" | "missing_input" | "spine_offline" | "run_failed";
  unit: string;
  name?: string;
  badge?: Badge;
  say: string; // the sentence she speaks — verbatim is fine
  runnable: Array<{ key: string; name: string; does: string }>; // ≤ 8 alternatives, by role relevance
}

// ---- alternatives by role relevance (≤ 8), never the whole list ----

const STOP = new Set([
  "the", "and", "for", "any", "run", "this", "with", "from", "into", "that", "his", "her", "king", "brandon", "churlish",
  "media", "fleet", "skill", "unit", "eve", "use", "when", "asked", "all", "every", "one", "not", "its", "are", "via",
  "which", "does", "generation", "python", "script", "binary", "mcp", "hold", "brain", "here", "workspace",
]);
// Crude stem: ads/ad, emails/email, documents/document, campaigns/campaign.
const stem = (w: string) => (w.length > 3 && /s$/.test(w) && !/ss$/.test(w) ? w.slice(0, -1) : w);
function words(s: string | undefined | null): Set<string> {
  const out = new Set<string>();
  for (const raw of (s ?? "").toLowerCase().split(/[^a-z0-9]+/)) {
    const w = stem(raw);
    if (w.length >= 2 && !STOP.has(w)) out.add(w);
  }
  return out;
}

export const MAX_ALTERNATIVES = 8;

/**
 * Up to 8 runnable units for a refusal, ranked by ROLE relevance to the unit he
 * named (its name, roster job/triggers/division, and — for a skill the sync
 * excluded — the exclusion reason), not by registry order. A word match beats
 * a shared division; pinned breaks ties. With nothing to match on, the pinned
 * units lead.
 */
export function alternativesFor(key: string, unit: FleetUnit | undefined): Capability[] {
  const want = words([key.replace(/-/g, " "), unit?.name, unit?.job, unit?.triggers, unit?.division, EXCLUDED.get(key)].join(" "));
  const scored = REGISTRY.map((c) => {
    const have = words([c.name, c.role ?? c.does, c.triggers, c.division, c.key.replace(/-/g, " ")].join(" "));
    let score = 0;
    for (const w of want) if (have.has(w)) score += 1;
    if (unit?.division && c.division === unit.division) score += 0.75;
    if (c.pinned) score += 0.25;
    return { c, score };
  });
  scored.sort((a, b) => b.score - a.score || Number(b.c.pinned) - Number(a.c.pinned) || a.c.name.localeCompare(b.c.name));
  return scored.slice(0, MAX_ALTERNATIVES).map((s) => s.c);
}

const altSentence = (alts: Capability[]) => alts.map((c) => `${c.key} (${c.does})`).join(", ");
const altList = (alts: Capability[]) => alts.map((c) => ({ key: c.key, name: c.name, does: c.does }));
const REROUTE = "If you hand it to one of them instead, tell him which unit ran it and why, in one clause.";

/** The spoken error for a unit that exists but has no runner here, or does not exist at all. */
export function refuseUnit(key: string, unit: FleetUnit | undefined): DispatchRefusal {
  const alts = alternativesFor(key, unit);
  if (!unit) {
    const reason = EXCLUDED.get(key);
    if (reason) {
      // A skill he has on disk that the sync classified WORKSPACE_ONLY — say why.
      const name = key.split("-").map((w) => (w ? w[0].toUpperCase() + w.slice(1) : w)).join(" ");
      return {
        ok: false,
        code: "unit_not_runnable",
        unit: key,
        name,
        badge: "WORKSPACE_ONLY",
        say:
          `I don't have a runner for ${name} — it's WORKSPACE_ONLY from here (${reason}). ` +
          `Closest units that can run from here: ${altSentence(alts)}. ${REROUTE}`,
        runnable: altList(alts),
      };
    }
    return {
      ok: false,
      code: "unit_unknown",
      unit: key,
      say:
        `I don't have a runner for "${key}" — no unit by that name is on the roster. ` +
        `Closest units that can run from here: ${altSentence(alts)}. ${REROUTE}`,
      runnable: altList(alts),
    };
  }
  const where = unit.loc === "CC" ? "a Claude Code unit" : unit.loc === "OS" ? "an OS-side unit" : "a workspace skill";
  const trigger = unit.triggers ? ` (trigger: ${unit.triggers})` : "";
  const reason = EXCLUDED.get(key);
  return {
    ok: false,
    code: "unit_not_runnable",
    unit: key,
    name: unit.name,
    badge: badgeFor(key),
    say:
      `I don't have a runner for ${unit.name} — it's ${where}${trigger}, WORKSPACE_ONLY from here` +
      `${reason ? ` (${reason})` : ""}. ` +
      `Closest units that can run from here: ${altSentence(alts)}. ${REROUTE}`,
    runnable: altList(alts),
  };
}

