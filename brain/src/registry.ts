export interface FleetUnitView {
  key: string;
  name: string;
  role: string;
  badge: Badge;
  live: boolean; // the runner is wired + reachable right now (false for every WORKSPACE_ONLY unit)
  roster: boolean; // false = a brain-only unit not on the OS roster (research, jimmy-olsen, …)
  division: string;
  loc: string;
  kind: Kind | null; // v0.2: worker | tool | skill; null when WORKSPACE_ONLY
  pinned: boolean; // v0.2: surfaced on THE CORE by default
  triggers: string; // v0.2: short trigger phrases (≤ ~80 chars); "" when unknown
  tier?: UnitTier; // v0.2: the unit's default tier; present only for RUNNABLE/DESK units
  lastRunAt?: string; // newest job created_at for this unit INSIDE the /state jobs window; absent = none
}

export interface FleetBlock {
  registered: number; // units.length
  dispatchable: number; // badge === RUNNABLE
  pinned: number; // v0.2: units with pinned:true
  kinds: { worker: number; tool: number; skill: number }; // v0.2: registry units by runner kind
  source: "os" | "bundled"; // where the roster membership came from this read
  at: string; // when that roster view was built
  units: FleetUnitView[];
}

function shortTriggers(s: string, max = 80): string {
  const t = s.replace(/\s+/g, " ").trim();
  if (t.length <= max) return t;
  let out = "";
  for (const p of t.split(" · ")) {
    const next = out ? `${out} · ${p}` : p;
    if (next.length > max) break;
    out = next;
  }
  return out || t.slice(0, max - 1) + "…";
}

function kindCounts(): FleetBlock["kinds"] {
  const kinds = { worker: 0, tool: 0, skill: 0 };
  for (const c of REGISTRY) kinds[c.runner.kind] += 1;
  return kinds;
}

export async function buildFleetBlock(jobs: ReadonlyArray<{ unit: string | null; created_at: string }>): Promise<FleetBlock> {
  const view = await fleetRoster();
  const lastRun = new Map<string, string>();
  for (const j of jobs) {
    if (!j.unit) continue;
    const prev = lastRun.get(j.unit);
    if (!prev || j.created_at > prev) lastRun.set(j.unit, j.created_at);
  }
  const units: FleetUnitView[] = view.units.map((u) => {
    const cap = byKey.get(u.key);
    return {
      key: u.key,
      name: u.name,
      role: u.job || cap?.does || "",
      badge: badgeFor(u.key),
      live: runnerLive(u.key),
      roster: true,
      division: u.division,
      loc: u.loc,
      kind: cap?.runner.kind ?? null,
      pinned: cap?.pinned ?? false,
      triggers: shortTriggers(u.triggers || cap?.triggers || ""),
      ...(cap ? { tier: cap.tier } : {}),
      ...(lastRun.has(u.key) ? { lastRunAt: lastRun.get(u.key)! } : {}),
    };
  });
  // Brain-only units (research, and skills with no roster row) are real runners that are not roster rows.
  for (const c of REGISTRY) {
    if (units.some((u) => u.key === c.key)) continue;
    units.push({
      key: c.key,
      name: c.name,
      role: c.does,
      badge: badgeFor(c.key),
      live: runnerLive(c.key),
      roster: false,
      division: c.division ?? (c.runner.kind === "skill" ? "brain-skills" : "brain-workers"),
      loc: "BRAIN",
      kind: c.runner.kind,
      pinned: c.pinned,
      triggers: shortTriggers(c.triggers ?? ""),
      tier: c.tier,
      ...(lastRun.has(c.key) ? { lastRunAt: lastRun.get(c.key)! } : {}),
    });
  }
  return {
    registered: units.length,
    dispatchable: units.filter((u) => u.badge === "RUNNABLE").length,
    pinned: units.filter((u) => u.pinned).length,
    kinds: kindCounts(),
    source: view.live ? "os" : "bundled",
    at: new Date(view.at).toISOString(),
    units,
  };
}

/** Cheap, synchronous registry counts for /health.fleet (no roster refresh). */
export function registryCounts(): { dispatchable: number; kinds: FleetBlock["kinds"]; pinned: number; manifest: ManifestStatus } {
  return {
    dispatchable: REGISTRY.filter((c) => badgeFor(c.key) === "RUNNABLE").length,
    kinds: kindCounts(),
    pinned: REGISTRY.filter((c) => c.pinned).length,
    manifest: manifestStatus,
  };
}

// ---- the ambient fleet line (D-DISPATCH §2.3 layer 1) — under ~90 tokens, every turn ----
// v0.2: counts per badge + the pinned names ONLY. Forty-odd runnable names do
// not fit in the pack; dispatch_unit matches them by name and fleet_roster
// lists them. The re-route clause is here because it is the one behaviour
// that must hold on every turn, tool call or not.
export async function fleetLine(): Promise<string> {
  const view = await fleetRoster();
  const rosterKeys = new Set(view.units.map((u) => u.key));
  const registered = view.units.length + REGISTRY.filter((c) => !rosterKeys.has(c.key)).length;
  let run = 0;
  let desk = 0;
  for (const c of REGISTRY) badgeFor(c.key) === "DESK" ? (desk += 1) : (run += 1);
  const wsOnly = registered - run - desk;
  const pinned = REGISTRY.filter((c) => c.pinned).map((c) => c.key);
  // Measured with the real tokenizer (count_tokens, 2026-09-01): hyphenated
  // keys and WORKSPACE_ONLY are token-expensive, so DESK is named only when
  // something is desk-wired and the badge word appears once.
  return (
    `Fleet: ${registered} units — ${run} RUNNABLE, ${desk ? `${desk} DESK, ` : ""}${wsOnly} WORKSPACE_ONLY${view.live ? "" : " (cached)"}. ` +
    `dispatch_unit runs them by name; fleet_roster lists them; others can't run here. ` +
    `Pinned: ${pinned.join(", ")}. ` +
    `Re-routing? say which unit and why.`
  );
}

