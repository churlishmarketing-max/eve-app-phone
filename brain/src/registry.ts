// THE CAPABILITY REGISTRY (D-DISPATCH §2.2). Capability is CODE, not data the
// OS can write: a registry row can only SELECT an adapter that already exists
// here (a worker doctrine, or a named tool adapter in dispatch.ts). It cannot
// name an executable, a path, or a tool grant. Doctrine text is the only thing
// a row carries that shapes behaviour, and workers hold no send tools.
//
// v0.2 — DATA-DRIVEN SKILLS. skills/MANIFEST.json (generated by
// scripts/sync-skills.mjs from his on-disk skills) is loaded at boot and merged
// with the code rows below; code rows win on conflict. A manifest row is a
// "skill" kind: its runner IS the existing SDK-subagent worker path
// (dispatch.ts runWorker) with the skill's SKILL.md + bundled text references
// as the system prompt. A SKILL.md is a system prompt — text in, text out —
// which is exactly the shape the four code workers already run as. The
// manifest cannot widen anything: kind is fixed to "skill", the tool list is
// the worker's (WebSearch/WebFetch, no send tools), the caps are the worker's.
//
// Everything else on the roster is badged honestly (WORKSPACE_ONLY) and is
// NEVER run. An unknown or unrunnable unit is a spoken refusal that names up
// to 8 alternatives by role relevance — never a silent substitution.

export type Badge = "RUNNABLE" | "DESK" | "WORKSPACE_ONLY";
export type Host = "brain" | "desk";
/** A unit's DEFAULT tier (fleet doctrine): green acts on its own, yellow drafts then waits for him, red needs his approve to act. */
export type UnitTier = "green" | "yellow" | "red";

export interface WorkerRunner {
  kind: "worker";
  doctrine: string; // the subagent's system prompt
  cost: { maxTurns: number; maxBudgetUsd: number; minutes: number };
}

export interface SkillRunner {
  kind: "skill";
  doctrine: string; // SKILL.md + bundled text references, assembled at boot
  cost: { maxTurns: number; maxBudgetUsd: number; minutes: number };
  files: string[]; // what the doctrine was assembled from (relative to skills/<key>/)
}

export interface ToolRunner {
  kind: "tool";
  adapter: "os_client_email"; // a key into dispatch.ts's TOOL_ADAPTERS — code, not data
  tier: "green" | "red"; // the tier of the job's LAST step (the send card for email)
  inputs: Array<{ name: "client"; required: boolean }>;
}

export type Runner = WorkerRunner | SkillRunner | ToolRunner;
export type Kind = Runner["kind"];

