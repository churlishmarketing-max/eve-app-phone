const here = path.dirname(fileURLToPath(import.meta.url));
const skillsDir = path.join(here, "..", "skills");

interface ManifestUnit {
  key: string;
  name: string;
  role: string;
  triggers: string;
  division: string | null;
  kind: "skill";
  tier: UnitTier;
  cost: { maxTurns: number; maxBudgetUsd: number; minutes: number };
  pinned: boolean;
  files: string[];
  bytes: number;
  note?: string;
}
interface Manifest {
  generatedAt: string;
  units: ManifestUnit[];
  excluded: Array<{ key: string; reason: string }>;
}

export interface ManifestStatus {
  loaded: boolean;
  units: number; // skill rows that made it into the registry
  excluded: number; // WORKSPACE_ONLY verdicts carried for honest refusals
  generatedAt: string | null;
  error?: string; // why loaded is false, or which units were dropped
}

let manifestStatus: ManifestStatus = { loaded: false, units: 0, excluded: 0, generatedAt: null, error: "not loaded" };
const EXCLUDED = new Map<string, string>(); // key → reason (WORKSPACE_ONLY by classification)

function skillPreamble(u: ManifestUnit): string {
  return (
    `You are ${u.name}, running as a Churlish Media fleet worker for Brandon King, dispatched by EVE. ` +
    "Your doctrine is the skill file below with its references inlined after it — you have NO file system, " +
    "so everything the skill tells you to read is already here; anything it says to look up on disk that is " +
    "not here, flag as [NEEDS: …]. You hold NO send, post, publish, schedule, or save tools: produce the " +
    "deliverable only. Anything the skill says to send, post, publish, schedule, or file is DRAFTED into the " +
    "deliverable and waits for his approval. " +
    (u.note ? `Brain-side limit for this unit: ${u.note}. ` : "") +
    "\n\n===== SKILL.md =====\n"
  );
}

function assembleDoctrine(u: ManifestUnit): string | null {
  const dir = path.join(skillsDir, u.key);
  let skill: string;
  try {
    skill = readFileSync(path.join(dir, "SKILL.md"), "utf8");
  } catch {
    return null;
  }
  let out = skillPreamble(u) + skill;
  for (const f of u.files) {
    if (f === "SKILL.md") continue;
    try {
      out += `\n\n===== bundled reference: ${f} =====\n` + readFileSync(path.join(dir, f), "utf8");
    } catch {
      out += `\n\n===== bundled reference: ${f} ===== [NEEDS: file missing from the bundle]`;
    }
  }
  return out + "\n\n===== LAW =====\n" + BASE_LAW;
}

// "Iris West — the fresh-fuel reporter for Brandon King's Churlish Media EVE
// fleet. Sweeps…" → "the fresh-fuel reporter". Short enough for the refusal
// sentence and the ambient line; the full role stays on /state.fleet.
function shortDoes(role: string, name: string, max = 60): string {
  let t = role.replace(/\s+/g, " ").trim();
  const lead = new RegExp(`^${name.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}\\s*[—–-]\\s*`, "i");
  t = t.replace(lead, "");
  t = t.replace(/\s+(for|of|inside|in)\s+(Brandon King|Churlish Media|Brandon's|the Churlish)[^.;:]*/i, "");
  t = t.split(/[.;:]\s/)[0].replace(/[.;:]$/, "").trim();
  if (t.length <= max) return t;
  return t.slice(0, max - 1).replace(/\s+\S*$/, "") + "…";
}

function loadManifest(codeKeys: Set<string>): Capability[] {
  let m: Manifest;
  try {
    m = JSON.parse(readFileSync(path.join(skillsDir, "MANIFEST.json"), "utf8")) as Manifest;
  } catch (e) {
    manifestStatus = { loaded: false, units: 0, excluded: 0, generatedAt: null, error: `skills/MANIFEST.json unreadable: ${e instanceof Error ? e.message : String(e)}` };
    return [];
  }
  const rows: Capability[] = [];
  const dropped: string[] = [];
  for (const u of m.units ?? []) {
    if (u.kind !== "skill" || !u.key || !u.name) {
      dropped.push(`${u.key ?? "?"} (bad row)`);
      continue;
    }
    if (codeKeys.has(u.key)) {
      console.log(`[registry] manifest row "${u.key}" conflicts with a code row — code wins`);
      continue;
    }
    const doctrine = assembleDoctrine(u);
    if (!doctrine) {
      dropped.push(`${u.key} (SKILL.md missing)`);
      continue;
    }
    rows.push({
      key: u.key,
      name: u.name,
      host: "brain",
      does: shortDoes(u.role, u.name),
      role: u.role,
      pinned: !!u.pinned,
      tier: u.tier === "green" || u.tier === "red" ? u.tier : "yellow",
      triggers: u.triggers || undefined,
      division: u.division || undefined,
      origin: "manifest",
      runner: {
        kind: "skill",
        doctrine,
        cost: {
          maxTurns: Math.min(u.cost?.maxTurns ?? STD_COST.maxTurns, 32),
          maxBudgetUsd: Math.min(u.cost?.maxBudgetUsd ?? STD_COST.maxBudgetUsd, 3),
          minutes: Math.min(u.cost?.minutes ?? STD_COST.minutes, 20),
        },
        files: u.files ?? ["SKILL.md"],
      },
    });
  }
  for (const x of m.excluded ?? []) if (x.key && !codeKeys.has(x.key)) EXCLUDED.set(x.key, x.reason);
  manifestStatus = {
    loaded: true,
    units: rows.length,
    excluded: EXCLUDED.size,
    generatedAt: m.generatedAt ?? null,
    ...(dropped.length ? { error: `dropped: ${dropped.join(", ")}` } : {}),
  };
  console.log(`[registry] skills manifest: ${rows.length} skill units loaded (generated ${m.generatedAt ?? "?"})${dropped.length ? `; dropped ${dropped.join(", ")}` : ""}`);
  return rows;
}

